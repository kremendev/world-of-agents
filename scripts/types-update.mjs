// npm run types:update: copies the mods API types for the installed Claude Code into tools/claude-code-types/index.d.ts.
//
// The source is the file the plugin-authoring skill writes when it loads, one per Claude Code version, under the temp
// folder. The engine's file also carries this machine's tool tables after the two modules, so only the two modules are
// kept: `claude-code` and `claude-code/testing`. Then the result is searched for local paths, the account name and email
// addresses, and nothing is written if any turns up. `npm run check` never runs this: the types change only on purpose.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir, userInfo } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const OUT = resolve(import.meta.dirname, '../tools/claude-code-types/index.d.ts');
const TABLES = "// The inputs of the built-in tools this build has, from each tool's";
const MODULES = ["declare module 'claude-code' {", "declare module 'claude-code/testing' {"];

function fail(message) {
  console.error(`types:update: ${message}`);
  process.exit(1);
}

const ran = spawnSync('claude', ['--version'], { encoding: 'utf8' });
const version = /^(\d+\.\d+\.\d+)/.exec(ran.stdout ?? '')?.[1];
if (!version) fail('could not read the version from `claude --version`. Is Claude Code on the PATH?');

const skills = join(tmpdir(), 'claude', 'bundled-skills', version);
const sources = existsSync(skills)
  ? readdirSync(skills)
      .map((hash) => join(skills, hash, 'plugin-authoring', 'types', 'claude-code.d.ts'))
      .filter((path) => existsSync(path))
      .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs)
  : [];
const source = sources[0];
if (!source) {
  fail(
    `no types for Claude Code ${version} yet. The plugin-authoring skill writes them when it loads: in a Claude Code ` +
      `session of this version, type /plugin-authoring (or ask it to make a mod), then run this again.`,
  );
}

const text = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
if (!text.startsWith(`// Written by Claude Code ${version}.`)) {
  fail(`${source} does not say it was written by Claude Code ${version}.`);
}
const cut = text.indexOf(`\n${TABLES}`);
if (cut < 0)
  fail("could not find where the tool tables start: the file's layout changed, so check it by hand.");
const kept = text.slice(0, cut).trimEnd() + '\n';

const modules = kept.split('\n').filter((line) => line.startsWith('declare module'));
if (JSON.stringify(modules) !== JSON.stringify(MODULES)) {
  fail(`expected exactly the two modules ${MODULES.join(' and ')}, found: ${modules.join(', ')}`);
}

// Nothing personal may go into the repo. Example addresses on reserved domains (RFC 2606) are fine.
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const home = homedir();
const user = userInfo().username;
const checks = [
  ['a Windows user folder', /[a-z]:[\\/]+users[\\/]/i],
  ['a macOS or Linux home folder', /\/(users|home)\/[^/\s"'`]+/i],
  ['this home folder', new RegExp(`${escape(home)}|${escape(home.replace(/\\/g, '/'))}`, 'i')],
  ['the account name', new RegExp(`\\b${escape(user)}\\b`, 'i')],
  ['an email address', /[\w.%+-]+@(?!example\.(?:com|org|net)\b)[\w-]+(?:\.[\w-]+)+/i],
];
const found = kept
  .split('\n')
  .flatMap((line, i) => checks.filter(([, re]) => re.test(line)).map(([what]) => `line ${i + 1}: ${what}`));
if (found.length > 0) fail(`not written, the types hold something personal:\n  ${found.join('\n  ')}`);

const header = [
  `// Generated by \`npm run types:update\` from the plugin-authoring skill's types for Claude Code ${version}.`,
  '// Only the mods API: the `claude-code` and `claude-code/testing` modules. The tool tables after them (this',
  "// machine's built-in and connected tools) are left out. Don't edit by hand: run the script again.",
  '',
].join('\n');
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, header + kept);
console.log(
  `types:update: wrote the mods API of Claude Code ${version} (${kept.split('\n').length} lines) to ${OUT}`,
);
